// Package codemap writes CODE_MAP.md: every tracked file of the repository, grouped by folder, each with the first
// sentence of its own header comment (a Go package or declaration comment, a Python docstring or banner, a script's
// synopsis). It reads nothing but the files themselves, so the map says what the code says about itself, and it is
// regenerated (`go run codemap_gen.go`), never edited by hand. TestCodeMapIsCurrent (codemap_test.go) fails when it
// is stale.
package codemap

import (
	"bufio"
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"unicode/utf8"
)

// Output is the map's file name at the repository root.
const Output = "CODE_MAP.md"

// maxSummary bounds one file's summary, in runes.
const maxSummary = 180

// skip reports whether a tracked file stays out of the map: dependency folders, Python caches and the map itself.
func skip(p string) bool {
	return p == Output || strings.Contains(p, "node_modules/") || strings.Contains(p, "__pycache__/")
}

// TrackedFiles lists the repository's tracked files under root, slash-separated, sorted.
func TrackedFiles(root string) ([]string, error) {
	cmd := exec.Command("git", "ls-files", "-z")
	cmd.Dir = root
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("git ls-files: %w", err)
	}
	var files []string
	for _, f := range strings.Split(string(out), "\x00") {
		if f != "" && !skip(f) {
			if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(f))); err == nil {
				files = append(files, f)
			}
		}
	}
	sort.Strings(files)
	return files, nil
}

// Generate returns the map's text for the given tracked files under root.
func Generate(root string, files []string) ([]byte, error) {
	byDir := map[string][]string{}
	for _, f := range files {
		d := path.Dir(f)
		byDir[d] = append(byDir[d], f)
	}
	dirs := make([]string, 0, len(byDir))
	for d := range byDir {
		dirs = append(dirs, d)
	}
	sort.Strings(dirs)

	var b bytes.Buffer
	b.WriteString("# Code map\n\n")
	b.WriteString("Generated by `go run codemap_gen.go` from each file's own header comment; do not edit by hand. ")
	b.WriteString("A file with no summary has no header comment: give it one, then regenerate. ")
	b.WriteString("For how the parts fit together, read [docs/architecture.md](docs/architecture.md).\n\n")
	fmt.Fprintf(&b, "%d files in %d folders.\n", len(files), len(dirs))

	top := ""
	for _, d := range dirs {
		t := strings.SplitN(d, "/", 2)[0]
		if t != top {
			top = t
			name := t
			if t == "." {
				name = "Root"
			}
			fmt.Fprintf(&b, "\n## %s\n", name)
		}
		pkg := ""
		var lines []string
		for _, f := range byDir[d] {
			raw, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(f)))
			if err != nil {
				return nil, err
			}
			sum, pkgDoc := Summarize(f, raw)
			if pkgDoc != "" && (pkg == "" || strings.HasSuffix(f, "/doc.go")) {
				pkg = pkgDoc
			}
			line := "- `" + path.Base(f) + "`"
			if sum != "" {
				line += ": " + sum
			}
			lines = append(lines, line)
		}
		title := "`" + d + "/`"
		if d == "." {
			title = "`/`"
		}
		fmt.Fprintf(&b, "\n### %s\n\n", title)
		if pkg != "" {
			b.WriteString(pkg + "\n\n")
		}
		for _, l := range lines {
			b.WriteString(l + "\n")
		}
	}
	return b.Bytes(), nil
}

// Summarize returns a file's one-sentence summary and, for a Go file with a package comment, that comment's first
// sentence as the package's summary. Binary files and files with no header comment get none.
func Summarize(name string, raw []byte) (summary, pkg string) {
	if !utf8.Valid(raw) || bytes.IndexByte(raw, 0) >= 0 {
		return "", ""
	}
	src := strings.ReplaceAll(string(raw), "\r\n", "\n")
	base := path.Base(name)
	switch ext := strings.ToLower(path.Ext(base)); {
	case ext == ".go":
		return goSummary(src)
	case ext == ".py":
		return sentence(pySummary(src)), ""
	case ext == ".ps1":
		return sentence(psSummary(src)), ""
	case ext == ".sh" || ext == ".cfg" || ext == ".toml" || ext == ".yml" || ext == ".yaml" ||
		strings.HasSuffix(base, "Dockerfile") || base == ".gitignore" || base == ".gitattributes" || ext == "":
		return sentence(hashSummary(src)), ""
	case ext == ".md":
		return sentence(mdSummary(src)), ""
	case ext == ".js" || ext == ".css" || ext == ".tla" || ext == ".nsh":
		return sentence(slashSummary(src)), ""
	case ext == ".html":
		return sentence(htmlSummary(src)), ""
	}
	return "", ""
}

// goSummary reads a Go file's package comment, else the doc comment of its first documented declaration.
func goSummary(src string) (string, string) {
	f, err := parser.ParseFile(token.NewFileSet(), "", src, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		return "", ""
	}
	if f.Doc != nil {
		s := sentence(f.Doc.Text())
		return s, s
	}
	// The first documented exported declaration says most about a file; a test file's first test, or the first
	// documented declaration of any kind, stands in.
	first := ""
	for _, d := range f.Decls {
		var doc *ast.CommentGroup
		exported := false
		switch d := d.(type) {
		case *ast.FuncDecl:
			doc, exported = d.Doc, d.Name.IsExported()
		case *ast.GenDecl:
			doc = d.Doc
			for _, s := range d.Specs {
				switch s := s.(type) {
				case *ast.TypeSpec:
					exported = exported || s.Name.IsExported()
					if doc == nil && len(d.Specs) == 1 {
						doc = s.Doc
					}
				case *ast.ValueSpec:
					for _, n := range s.Names {
						exported = exported || n.IsExported()
					}
				}
			}
		}
		if doc == nil || strings.HasPrefix(strings.TrimSpace(doc.Text()), "go:") {
			continue
		}
		if exported {
			return sentence(doc.Text()), ""
		}
		if first == "" {
			first = sentence(doc.Text())
		}
	}
	return first, ""
}

var (
	docstring = regexp.MustCompile(`(?s)^(?:[rRuU]?)("""|''')(.*?)("""|''')`)
	banner    = regexp.MustCompile(`^[=\-#*~_ ]*$`)
)

// pySummary reads a Python module's docstring, else its first comment block that is not a shebang, coding line or
// banner rule (the agent's files open with a "# ====" banner after their imports).
func pySummary(src string) string {
	body := strings.TrimLeft(skipLeadingHash(src), "\n ")
	if m := docstring.FindStringSubmatch(body); m != nil {
		return m[2]
	}
	return hashSummary(src)
}

// skipLeadingHash drops the leading lines that are comments or blank, so a docstring after a header comment is found.
func skipLeadingHash(src string) string {
	sc := bufio.NewScanner(strings.NewReader(src))
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	var rest []string
	started := false
	for sc.Scan() {
		l := sc.Text()
		if !started {
			t := strings.TrimSpace(l)
			if t == "" || strings.HasPrefix(t, "#") {
				continue
			}
			started = true
		}
		rest = append(rest, l)
	}
	return strings.Join(rest, "\n")
}

// hashSummary returns the first block of '#' comment lines, skipping shebangs, coding and directive lines, and banner
// rules; the block ends at the first line that is not a comment.
func hashSummary(src string) string {
	var block []string
	for _, l := range strings.Split(src, "\n") {
		t := strings.TrimSpace(l)
		if !strings.HasPrefix(t, "#") {
			if len(block) > 0 {
				break
			}
			continue
		}
		if strings.HasPrefix(t, "#!") || strings.Contains(t, "-*- coding") || strings.HasPrefix(t, "# syntax=") ||
			strings.HasPrefix(t, "#requires") || strings.HasPrefix(t, "#Requires") {
			continue
		}
		text := strings.TrimSpace(strings.TrimLeft(t, "#"))
		if banner.MatchString(text) {
			if len(block) > 0 && text == "" {
				break
			}
			continue
		}
		block = append(block, text)
	}
	return strings.Join(block, " ")
}

// psSummary reads a PowerShell script's .SYNOPSIS, else its first '#' comment block.
func psSummary(src string) string {
	if i := strings.Index(src, ".SYNOPSIS"); i >= 0 {
		var block []string
		for _, l := range strings.Split(src[i+len(".SYNOPSIS"):], "\n")[1:] {
			t := strings.TrimSpace(l)
			if t == "" || strings.HasPrefix(t, ".") || strings.HasPrefix(t, "#>") {
				break
			}
			block = append(block, t)
		}
		return strings.Join(block, " ")
	}
	return hashSummary(src)
}

// mdSummary returns a Markdown file's first heading.
func mdSummary(src string) string {
	for _, l := range strings.Split(src, "\n") {
		if t := strings.TrimSpace(l); strings.HasPrefix(t, "#") {
			return strings.TrimSpace(strings.TrimLeft(t, "#"))
		}
	}
	return ""
}

// slashSummary returns the first // or /* */ comment block of a JavaScript, CSS or TLA+ file.
func slashSummary(src string) string {
	t := strings.TrimSpace(src)
	if strings.HasPrefix(t, "/*") {
		if end := strings.Index(t, "*/"); end > 0 {
			return strings.Trim(strings.ReplaceAll(t[2:end], "\n", " "), "* ")
		}
	}
	var block []string
	for _, l := range strings.Split(src, "\n") {
		s := strings.TrimSpace(l)
		if strings.HasPrefix(s, "//") || strings.HasPrefix(s, "\\*") || strings.HasPrefix(s, ";") {
			text := strings.TrimSpace(strings.TrimLeft(s, "/\\*; "))
			if banner.MatchString(text) {
				if len(block) > 0 {
					break
				}
				continue
			}
			block = append(block, text)
			continue
		}
		if len(block) > 0 || (s != "" && !strings.HasPrefix(s, "'use strict'") && !strings.HasPrefix(s, "\"use strict\"")) {
			break
		}
	}
	return strings.Join(block, " ")
}

var (
	htmlComment = regexp.MustCompile(`(?s)<!--(.*?)-->`)
	htmlTitle   = regexp.MustCompile(`(?is)<title>(.*?)</title>`)
)

// htmlSummary returns a page's first comment, else its title.
func htmlSummary(src string) string {
	head := src
	if len(head) > 4000 {
		head = head[:4000]
	}
	if m := htmlComment.FindStringSubmatch(head); m != nil {
		return m[1]
	}
	if m := htmlTitle.FindStringSubmatch(head); m != nil && !strings.Contains(m[1], "{{") {
		return "Page: " + strings.TrimSpace(m[1])
	}
	return ""
}

var spaces = regexp.MustCompile(`\s+`)

// sentence keeps a summary's first sentence on one line, cut to maxSummary runes, with Markdown table pipes escaped.
func sentence(s string) string {
	s = strings.TrimSpace(spaces.ReplaceAllString(s, " "))
	for i := 0; i+1 < len(s); i++ {
		if (s[i] == '.' || s[i] == '!' || s[i] == '?') && s[i+1] == ' ' && !abbrev(s[:i]) {
			s = s[:i+1]
			break
		}
	}
	if r := []rune(s); len(r) > maxSummary {
		s = strings.TrimSpace(string(r[:maxSummary-1])) + "…"
	}
	return strings.ReplaceAll(s, "|", `\|`)
}

// abbrev reports whether the text before a full stop ends in a short abbreviation (e.g., i.e., vs., a file name's
// dot is not followed by a space, so it never reaches here).
func abbrev(before string) bool {
	for _, a := range []string{"e.g", "i.e", "vs", "etc", "cf", "Dr", "Mr", "Ms", "No"} {
		if strings.HasSuffix(before, " "+a) || before == a || strings.HasSuffix(before, "("+a) {
			return true
		}
	}
	return false
}
