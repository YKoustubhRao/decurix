import threading
import time

from flowera_agent import config, state
from flowera_agent.harness import continue_after_help, perform_task
from flowera_agent.logging_utils import log
from flowera_agent.messaging import send_helptext


# ============================================================
# Command watcher
# ============================================================

def command_watcher():
    """
    Continuously watch command/ for new task files.
    """

    log(
        f"Watching command directory: "
        f"{config.COMMAND_DIR}"
    )

    while True:

        try:

            files = sorted(
                config.COMMAND_DIR.glob("*.txt"),
                key=lambda p: p.stat().st_mtime,
            )

            for path in files:

                if path.name in state.processed_commands:
                    continue

                # Ignore files generated by the agent.
                if path.name.startswith("result_"):
                    state.processed_commands.add(
                        path.name
                    )
                    continue

                try:
                    content = path.read_text(
                        encoding="utf-8"
                    ).strip()

                except Exception as exc:
                    log(
                        f"Could not read {path}: "
                        f"{exc}"
                    )
                    continue

                if not content:
                    state.processed_commands.add(
                        path.name
                    )
                    continue

                state.processed_commands.add(
                    path.name
                )

                # If the agent is waiting for human help,
                # this new command is the help response.
                if state.waiting_for_help:

                    thread = threading.Thread(
                        target=continue_after_help,
                        args=(content,),
                        daemon=True,
                    )

                    thread.start()

                    continue

                # Do not start another task while one
                # is already running.
                if state.current_task is not None:

                    log(
                        "Task already running. "
                        f"Leaving {path.name} "
                        "for later."
                    )

                    state.processed_commands.discard(
                        path.name
                    )

                    continue

                thread = threading.Thread(
                    target=perform_task,
                    args=(
                        content,
                        path,
                    ),
                    daemon=True,
                )

                thread.start()

        except Exception as exc:
            log(
                f"Command watcher error: {exc}"
            )

        time.sleep(1)


# ============================================================
# Help text watcher (defunct, useful to have)
# ============================================================

def helptext_watcher():
    """
    Existing functionality:
    watches helptext/ and sends newly-created or
    modified .txt files to the control plane.

    This remains useful for agent-generated help requests.
    """

    log(
        f"Watching helptext directory: "
        f"{config.HELPTEXT_DIR}"
    )

    seen = {}

    while True:

        try:

            for path in config.HELPTEXT_DIR.glob("*.txt"):

                try:
                    stat = path.stat()

                except FileNotFoundError:
                    continue

                signature = (
                    stat.st_mtime_ns,
                    stat.st_size,
                )

                if seen.get(path.name) == signature:
                    continue

                seen[path.name] = signature

                try:
                    content = path.read_text(
                        encoding="utf-8"
                    )

                except Exception as exc:
                    log(
                        f"Could not read help file "
                        f"{path}: {exc}"
                    )
                    continue

                send_helptext(
                    path.name,
                    content,
                )

        except Exception as exc:
            log(
                f"Helptext watcher error: "
                f"{exc}"
            )

        time.sleep(1)
